#!/usr/bin/env bash
#
# Prepare a fresh Ubuntu VPS to run Article Platform.
#
#   curl -fsSL https://raw.githubusercontent.com/YOU/REPO/main/deploy/bootstrap.sh | bash
#   -- or, if you copied the repo up by hand --
#   bash deploy/bootstrap.sh
#
# Installs Docker, creates the data directory, generates an encryption key,
# and starts the app bound to localhost only.
#
# Safe to run more than once: every step checks before acting, and an
# existing .env is never overwritten.

set -euo pipefail

APP_DIR="${APP_DIR:-$HOME/article-platform}"
PORT="${PORT:-8080}"

say()  { printf '\n\033[1;34m==>\033[0m %s\n' "$1"; }
warn() { printf '\033[1;33m  ! \033[0m%s\n' "$1"; }
ok()   { printf '\033[1;32m  ✓ \033[0m%s\n' "$1"; }

# --------------------------------------------------------------------------
say "Checking prerequisites"

if [ "$(id -u)" -eq 0 ]; then
  warn "Running as root. That works, but a normal user with sudo is safer."
  SUDO=""
else
  SUDO="sudo"
fi

if ! command -v curl >/dev/null 2>&1; then
  $SUDO apt-get update -qq && $SUDO apt-get install -y -qq curl
fi
ok "curl present"

# --------------------------------------------------------------------------
say "Installing Docker"

if command -v docker >/dev/null 2>&1; then
  ok "Docker already installed ($(docker --version))"
else
  curl -fsSL https://get.docker.com | $SUDO sh
  ok "Docker installed"
fi

if ! docker compose version >/dev/null 2>&1; then
  $SUDO apt-get update -qq
  $SUDO apt-get install -y -qq docker-compose-plugin
fi
ok "Docker Compose ready"

# Let the current user run docker without sudo.
if [ -n "$SUDO" ] && ! groups | grep -qw docker; then
  $SUDO usermod -aG docker "$USER"
  warn "Added $USER to the docker group — log out and back in for it to apply."
  warn "Until then, prefix docker commands with sudo."
fi

# --------------------------------------------------------------------------
say "Setting up $APP_DIR"

if [ ! -d "$APP_DIR" ]; then
  warn "$APP_DIR does not exist."
  warn "Copy the application there first, then re-run this script:"
  warn "  git clone <your-repo> $APP_DIR"
  warn "  # or from your machine:  rsync -av --exclude node_modules --exclude data ./app/ vps:$APP_DIR/"
  exit 1
fi

cd "$APP_DIR"
mkdir -p data
ok "data directory ready"

# --------------------------------------------------------------------------
say "Configuring"

if [ -f .env ]; then
  ok ".env already exists — leaving it untouched"
else
  KEY="$(openssl rand -hex 32)"
  cat > .env <<EOF
# Generated by deploy/bootstrap.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# This key encrypts stored credentials. Back it up. Losing it means
# re-entering every credential in the Settings UI.
ENCRYPTION_KEY=$KEY
PORT=$PORT
DB_PATH=/app/data/platform.db
LOG_LEVEL=info
EOF
  chmod 600 .env
  ok ".env created with a fresh encryption key"
fi

# --------------------------------------------------------------------------
say "Binding to localhost"

# The UI has no authentication, so it must not listen on a public interface.
# Rewrite the published port to loopback if it is not already.
if grep -qE '^\s*-\s*"[0-9]+:8080"' docker-compose.yml 2>/dev/null; then
  sed -i -E "s|^(\s*)- \"[0-9]+:8080\"|\1- \"127.0.0.1:${PORT}:8080\"|" docker-compose.yml
  ok "docker-compose.yml now publishes 127.0.0.1:${PORT} only"
else
  ok "port binding already restricted (or customised) — not changing it"
fi

# --------------------------------------------------------------------------
say "Building and starting"

DC="docker compose"
[ -n "$SUDO" ] && ! groups | grep -qw docker && DC="sudo docker compose"

$DC up -d --build

say "Waiting for the app to come up"
for i in $(seq 1 30); do
  if curl -fsS "http://127.0.0.1:${PORT}/healthz" >/dev/null 2>&1; then
    ok "Healthy"
    curl -fsS "http://127.0.0.1:${PORT}/healthz"; echo
    break
  fi
  [ "$i" -eq 30 ] && { warn "Did not become healthy in 30s. Logs:"; $DC logs --tail 40; exit 1; }
  sleep 1
done

# --------------------------------------------------------------------------
cat <<EOF

$(printf '\033[1;32m')Done.$(printf '\033[0m')

The UI is listening on 127.0.0.1:${PORT} and is NOT reachable from the
internet. That is deliberate: there is no login screen.

To open it from your own machine, forward the port over SSH:

    ssh -N -L ${PORT}:127.0.0.1:${PORT} $(whoami)@<this-server>

then browse to http://localhost:${PORT}

Next steps:
  1. Settings         — credentials and timezone
  2. LLM endpoints    — your Ollama servers
  3. Sites            — your websites
  4. Keywords         — import a CSV
  5. Enable automation once a manual "Run once now" succeeds

Useful commands (from $APP_DIR):
    docker compose logs -f          follow logs
    docker compose restart          restart
    docker compose down             stop
    docker compose up -d --build    redeploy after a code change

EOF
